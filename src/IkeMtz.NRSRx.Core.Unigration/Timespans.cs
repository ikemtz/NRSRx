namespace IkeMtz.NRSRx.Core.Unigration
{
  /// <summary>
  /// Provides millisecond constants for common time spans.
  /// </summary>
  public static class Timespans
  {
    /// <summary>
    /// The number of milliseconds in half a minute.
    /// </summary>
    public const int ThirtySeconds = 30_000;
    /// <summary>
    /// The number of milliseconds in one minute.
    /// </summary>
    public const int OneMinute = 60_000;

    /// <summary>
    /// The number of milliseconds in two minutes.
    /// </summary>
    public const int TwoMinutes = 120_000;

    /// <summary>
    /// The number of milliseconds in three minutes.
    /// </summary>
    public const int ThreeMinutes = 180_000;
  }
}
